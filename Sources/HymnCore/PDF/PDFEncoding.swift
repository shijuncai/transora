import Foundation

/// 简单字体的预定义编码表。
///
/// 什么时候需要它：字体**没有 `/ToUnicode`**，但声明了 `/Encoding /WinAnsiEncoding`
/// 之类的预定义编码。这在真实文档里非常常见——尤其是用系统字体（Arial、
/// Times New Roman）且**根本没嵌入字体文件**的 PDF。
///
/// 实测某本 400 页的书：136 页的召回只有 0.3–0.5，原因就是这些页的
/// ArialMT / TimesNewRomanPSMT 既没 `/ToUnicode` 也没嵌入字体，
/// 但声明了 `/WinAnsiEncoding`。补上编码表后召回回到 99.99%。
///
/// 只实现三种：WinAnsi（CP1252）、MacRoman、Standard。Symbolic 字体不做——
/// 那种编码没有公开的码位语义，硬猜只会产出乱码。
public enum PDFEncoding {
    public enum Kind: String, Sendable {
        case winAnsi = "WinAnsiEncoding"
        case macRoman = "MacRomanEncoding"
        case standard = "StandardEncoding"
        case pdfDoc = "PDFDocEncoding"
        case macExpert = "MacExpertEncoding"
    }

    /// 码 → unicode 字符串。找不到返回 nil（上层标记 unmapped，不猜）。
    public static func unicode(for kind: Kind, code: Int) -> String? {
        guard code >= 0, code <= 255 else { return nil }
        switch kind {
        case .winAnsi: return winAnsi[code]
        case .macRoman: return macRoman[code]
        case .standard: return standard[code]
        case .pdfDoc: return winAnsi[code]      // 差别极小，对正文无影响
        case .macExpert: return nil             // 专家字形集，不猜
        }
    }

    // MARK: WinAnsi（CP1252）

    static let winAnsi: [Int: String] = {
        var table: [Int: String] = [:]
        // 0x20–0x7E 与 ASCII 相同
        for code in 0x20...0x7E {
            if let scalar = UnicodeScalar(UInt32(code)) { table[code] = String(scalar) }
        }
        // 0x80–0x9F 是 CP1252 的特殊区
        let high: [Int: UInt32] = [
            0x80: 0x20AC, 0x82: 0x201A, 0x83: 0x0192, 0x84: 0x201E, 0x85: 0x2026,
            0x86: 0x2020, 0x87: 0x2021, 0x88: 0x02C6, 0x89: 0x2030, 0x8A: 0x0160,
            0x8B: 0x2039, 0x8C: 0x0152, 0x8E: 0x017D, 0x91: 0x2018, 0x92: 0x2019,
            0x93: 0x201C, 0x94: 0x201D, 0x95: 0x2022, 0x96: 0x2013, 0x97: 0x2014,
            0x98: 0x02DC, 0x99: 0x2122, 0x9A: 0x0161, 0x9B: 0x203A, 0x9C: 0x0153,
            0x9E: 0x017E, 0x9F: 0x0178,
        ]
        for (code, scalar) in high {
            if let value = UnicodeScalar(scalar) { table[code] = String(value) }
        }
        // 0xA0–0xFF 基本是 Latin-1，例外是 0xAD（软连字符在 PDF 里就是普通连字符）
        for code in 0xA0...0xFF {
            if let scalar = UnicodeScalar(UInt32(code)) { table[code] = String(scalar) }
        }
        table[0xAD] = "-"
        return table
    }()

    // MARK: MacRoman

    static let macRoman: [Int: String] = {
        var table: [Int: String] = [:]
        for code in 0x20...0x7E {
            if let scalar = UnicodeScalar(UInt32(code)) { table[code] = String(scalar) }
        }
        // 0x80–0xFF 的 MacRoman 映射（Adobe 官方表）
        let high: [UInt32] = [
            0x00C4, 0x00C5, 0x00C7, 0x00C9, 0x00D1, 0x00D6, 0x00DC, 0x00E1,
            0x00E0, 0x00E2, 0x00E4, 0x00E3, 0x00E5, 0x00E7, 0x00E9, 0x00E8,
            0x00EA, 0x00EB, 0x00ED, 0x00EC, 0x00EE, 0x00EF, 0x00F1, 0x00F3,
            0x00F2, 0x00F4, 0x00F6, 0x00F5, 0x00FA, 0x00F9, 0x00FB, 0x00FC,
            0x2020, 0x00B0, 0x00A2, 0x00A3, 0x00A7, 0x2022, 0x00B6, 0x00DF,
            0x00AE, 0x00A9, 0x2122, 0x00B4, 0x00A8, 0x2260, 0x00C6, 0x00D8,
            0x221E, 0x00B1, 0x2264, 0x2265, 0x00A5, 0x00B5, 0x2202, 0x2211,
            0x220F, 0x03C0, 0x222B, 0x00AA, 0x00BA, 0x03A9, 0x00E6, 0x00F8,
            0x00BF, 0x00A1, 0x00AC, 0x221A, 0x0192, 0x2248, 0x2206, 0x00AB,
            0x00BB, 0x2026, 0x00A0, 0x00C0, 0x00C3, 0x00D5, 0x0152, 0x0153,
            0x2013, 0x2014, 0x201C, 0x201D, 0x2018, 0x2019, 0x00F7, 0x25CA,
            0x00FF, 0x0178, 0x2044, 0x20AC, 0x2039, 0x203A, 0xFB01, 0xFB02,
            0x2021, 0x00B7, 0x201A, 0x201E, 0x2030, 0x00C2, 0x00CA, 0x00C1,
            0x00CB, 0x00C8, 0x00CD, 0x00CE, 0x00CF, 0x00CC, 0x00D3, 0x00D4,
            0xF8FF, 0x00D2, 0x00DA, 0x00DB, 0x00D9, 0x0131, 0x02C6, 0x02DC,
            0x00AF, 0x02D8, 0x02D9, 0x02DA, 0x00B8, 0x02DD, 0x02DB, 0x02C7,
        ]
        for (offset, scalar) in high.enumerated() {
            if let value = UnicodeScalar(scalar) { table[0x80 + offset] = String(value) }
        }
        return table
    }()

    // MARK: StandardEncoding

    static let standard: [Int: String] = {
        var table: [Int: String] = [:]
        for code in 0x20...0x7E {
            if let scalar = UnicodeScalar(UInt32(code)) { table[code] = String(scalar) }
        }
        // StandardEncoding 与 ASCII 的差异（引号与几个符号）
        table[0x27] = "\u{2019}"   // quoteright
        table[0x60] = "\u{2018}"   // quoteleft
        let high: [Int: UInt32] = [
            0xA1: 0x00A1, 0xA2: 0x00A2, 0xA3: 0x00A3, 0xA4: 0x2044, 0xA5: 0x00A5,
            0xA6: 0x0192, 0xA7: 0x00A7, 0xA8: 0x00A4, 0xA9: 0x0027, 0xAA: 0x201C,
            0xAB: 0x00AB, 0xAC: 0x2039, 0xAD: 0x203A, 0xAE: 0xFB01, 0xAF: 0xFB02,
            0xB1: 0x2013, 0xB2: 0x2020, 0xB3: 0x2021, 0xB4: 0x00B7, 0xB6: 0x00B6,
            0xB7: 0x2022, 0xB8: 0x201A, 0xB9: 0x201E, 0xBA: 0x201D, 0xBB: 0x00BB,
            0xBC: 0x2026, 0xBD: 0x2030, 0xBF: 0x00BF, 0xC1: 0x0060, 0xC2: 0x00B4,
            0xC3: 0x02C6, 0xC4: 0x02DC, 0xC5: 0x00AF, 0xC6: 0x02D8, 0xC7: 0x02D9,
            0xC8: 0x00A8, 0xCA: 0x02DA, 0xCB: 0x00B8, 0xCD: 0x02DD, 0xCE: 0x02DB,
            0xCF: 0x02C7, 0xD0: 0x2014, 0xE1: 0x00C6, 0xE3: 0x00AA, 0xE8: 0x0141,
            0xE9: 0x00D8, 0xEA: 0x0152, 0xEB: 0x00BA, 0xF1: 0x00E6, 0xF5: 0x0131,
            0xF8: 0x0142, 0xF9: 0x00F8, 0xFA: 0x0153, 0xFB: 0x00DF,
        ]
        for (code, scalar) in high {
            if let value = UnicodeScalar(scalar) { table[code] = String(value) }
        }
        return table
    }()
}
